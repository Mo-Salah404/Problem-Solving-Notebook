/*
    Problem: I. Palindrome
    Sheet: Sheet #2 — Loops

   Loops المسألة دي هتساعدنا نفهم إزاي نعكس أي رقم باستخدام 
    ونتعلم إزاي نستخرج الـ Digits ونتعامل معاها باستخدام
    Modulo (%) و Integer Division (/)

   ولا لأ Palindrome كمان هنتعلم إزاي نحدد إذا كان الرقم  
    عن طريق مقارنة الرقم الأصلي بالرقم المعكوس

    ❤️ بالتوفيق إن شاء الله

    =================================================================

    💡 A SMALL HINT          وتحاول بنفسك قبل ما تشوف الحل Hint  ضروري جدًا تشوف الـ 
  

    عشان نعكس أي رقم هنحتاج 3 خطوات

    1. Extract the last digit:  
       digit = n % 10;

    2. Build the reversed number:
       rev = rev * 10 + digit;

    3. Remove the last digit:
       n /= 10;

   لحد ما الرقم يخلص while loop كرر الخطوات دي باستخدام 
    وفي النهاية قارن الرقم الأصلي بالرقم المعكوس

    =================================================================

    🧠 IDEA: خلينا نفكر فيها ببساطة

    المطلوب مننا نطبع الرقم بالعكس وبعدها نحدد إذا كان
     ولا لأPalindrome

   original أول حاجة هنحتفظ بالرقم الأصلي في متغير 
    عشان نحتاجه في المقارنة بعدين
   while loop بعد كده هنبدأ نعكس الرقم باستخدام 

    في كل مرة
    - نستخرج آخر Digit باستخدام % 10.
    - نضيفه للرقم المعكوس باستخدام rev * 10 + digit.
    - نحذف آخر Digit باستخدام / 10.

    بعد ما نخلص، هنقارن original مع rev.

    لو متساويين يبقى الرقم Palindrome ونطبع YES.
    غير كده نطبع NO.

    =================================================================

    💡 IMPORTANT OBSERVATION

    لما نعكس رقم زي 160 الناتج بيكون 61 مش 061.

   Integer وده لأننا بنتعامل مع الرقم كـ 
    فالأصفار اللي في البداية بتختفي تلقائيًا

    =================================================================

    ⏱️ COMPLEXITY:

    Time Complexity: O(log n)
    Space Complexity: O(1)

    =================================================================

    Link:
    https://codeforces.com/group/MWSDmqGsZm/contest/219432/problem/I

     Progress Over Perfection 🎯
*/

// =================================================================

#include <iostream>
using namespace std;

int main()
{
    long long n;
    cin >> n;

    long long original = n;
    long long rev = 0;

    while (n > 0)
    {
        int digit = n % 10;

        rev = rev * 10 + digit;

        n /= 10;
    }

    cout << rev << '\n';

    if (original == rev)
        cout << "YES\n";
    else
        cout << "NO\n";

    return 0;
}

