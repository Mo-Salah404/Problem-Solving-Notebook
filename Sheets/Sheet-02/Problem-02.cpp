/*
    Problem: Primes from 1 to n
    Sheet: Sheet #2 — Loops

    المسألة دي هتساعدك تفهم إزاي نطلع كل الأعداد الأولية
   N من 1 لحد  Nested Loops ونتعلم إزاي نستخدم 
    مع تحسين بسيط يخلي الحل أسرع بكتير

   ❤️ بالتوفيق ان شاءالله 

    =================================================================

    💡 A SMALL HINT    ضروري جدا تشوف الهينت وتحاول بنفسك قبل ما تشوف الحل

    Prime مش كل رقم أكبر من 1 بيكون

   N عشان نعرف الأعداد الأولية من 1 لحد 
    X ابدأ من 2 وجرب كل رقم
    X لكل رقم جرب تقسمه على الأرقام من 2 لحد الجذر التربيعي بتاعه

    لو لقيت أي رقم بيقسمه بدون باقي
    X % j == 0
   Prime يبقى الرقم مش 

    لكن لو خلصت التجربة ومفيش أي رقم قسمه بدون باقي
    Prime يبقى الرقم

    =================================================================

    🧠 Idea:      خلينا نفكر فيها ببساطة

    Prime Number الـ
    هو عدد أكبر من 1
    وليه عاملين فقط
    1 العدد نفسه و
   N المطلوب إننا نطبع كل الأعداد الأولية من 1 لحد 

   Nested Loops عشان نحل المسألة هنستخدم 

   Loop أول 
   N هنبدأ من 2 لحد 
    وده عشان نختبر كل رقم لوحده

   Loop تاني 
    لكل رقم X هنبدأ نجرب نقسمه على الأرقام
   X من 2 لحد الجذر التربيعي بتاع 

   Prime في البداية هنفترض إن الرقم 
    bool isPrime = true;

   X لو لقينا أي رقم بيقسم 
    من غير اي باقي

    X % j == 0

   Prime يبقى الرقم مش 
   isPrime وهنغير قيمة 
   false إلى 
break هنستخدم
     عشان مش محتاجين نكمل
    
   Inner Loop لكن لو خلصنا الـ 
    وملاقيناش أي قاسم للرقم
   Prime يبقى الرقم 
    وهنطبعه

    =================================================================

    💡 Important Observation:

    ليه بنستخدم

    j * j <= i

   i - 1 بدل ما نجرب كل الأرقام لحد 

    لأن أي عدد مركب لازم يكون ليه عامل واحد على الأقل
    أصغر من أو يساوي الجذر التربيعي بتاعه
    يعني مش محتاجين نجرب كل الأرقام
    وده بيخلّي الحل أسرع بكتير

    =================================================================

    ⏱️ Complexity:

    Time: O(n√n)
    Space: O(1)

    Time Complexity:
   N عندنا 
   Outer Loop بتلف من 2 لحد 
    ولكل رقم بنعمل 
    Inner Loop لحد الجذر التربيعي بتاعه

    وبالتالي إجمالي عدد العمليات في أسوأ حالة
   O(n√n) بيكون 

    Space Complexity:
    O(1) المساحة

    لأننا بنستخدم عدد ثابت من المتغيرات
    ومش بنحتاج أي 
   إضافية Arrays أو Data Structures 
*/

// =================================================================
// =================================================================

#include <iostream>
using namespace std;

int main()
{
    int n;  
    cin >> n;

    for (int i = 2; i <= n; i++)
    {
        bool isPrime = true;

        for (int j = 2; j * j <= i; j++)    // c
        {
            if (i % j == 0)
            {
                isPrime = false;
                break;
            }
        }

        if (isPrime)    
            cout << i << " ";
    }

    return 0;
}

